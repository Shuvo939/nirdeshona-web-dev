import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const require = createRequire(new URL("../package.json", import.meta.url));
const colors = require("tailwindcss/colors");

const rgb = (hex) => { const h = hex.replace("#", ""); const n = h.length === 3 ? h.split("").map((c) => c + c).join("") : h; return [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16)); };
const mix = (a, b, t) => a.map((v, i) => Math.round(v * t + b[i] * (1 - t)));
const s = (c) => c.join(" ");
const STOPS = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"];
const HUES = ["red", "emerald", "amber", "blue", "sky", "green", "violet", "orange", "rose", "indigo", "lime"];
const PAGE = [18, 18, 18];

const light = {}, dark = {};
light["white"] = s([255, 255, 255]); dark["white"] = s(PAGE);
light["black"] = s([0, 0, 0]); dark["black"] = s([250, 250, 250]);
const neutralDark = { 50: 24, 100: 32, 200: 44, 300: 64, 400: 115, 500: 150, 600: 175, 700: 200, 800: 222, 900: 236, 950: 245 };
for (const st of STOPS) { light[`neutral-${st}`] = s(rgb(colors.neutral[st])); dark[`neutral-${st}`] = s(Array(3).fill(neutralDark[st])); }
for (const hue of HUES) {
  const p = colors[hue];
  for (const st of STOPS) light[`${hue}-${st}`] = s(rgb(p[st]));
  const c = (st) => rgb(p[st]);
  const d = {
    50: mix(c("500"), PAGE, 0.12), 100: mix(c("500"), PAGE, 0.2), 200: mix(c("500"), PAGE, 0.32), 300: mix(c("500"), PAGE, 0.5),
    400: c("400"), 500: c("500"), 600: c("400"), 700: c("300"), 800: c("200"), 900: c("100"), 950: c("50"),
  };
  for (const st of STOPS) dark[`${hue}-${st}`] = s(d[st]);
}
const block = (sel, vals) => `${sel} {\n${Object.entries(vals).map(([k, v]) => `  --c-${k}: ${v};`).join("\n")}\n}\n`;
const css = `/* Generated by scripts/gen-theme.mjs — colour tokens for light and dark mode.
   Tailwind colours read these variables, so html.dark switches the whole site. */
${block(":root", light)}
${block("html.dark", dark)}
/* Panels that are dark by design (footer, highlighted cards) keep their light-mode tokens. */
${block("html.dark .theme-fixed", light)}
html.dark { color-scheme: dark; }
`;
writeFileSync(new URL("../app/theme.css", import.meta.url), css);

const cfg = { white: "rgb(var(--c-white) / <alpha-value>)", black: "rgb(var(--c-black) / <alpha-value>)" };
for (const fam of ["neutral", ...HUES]) { cfg[fam] = {}; for (const st of STOPS) cfg[fam][st] = `rgb(var(--c-${fam}-${st}) / <alpha-value>)`; }
writeFileSync(new URL("../lib/theme-colors.json", import.meta.url), JSON.stringify(cfg, null, 2));
console.log("ok", Object.keys(light).length, "tokens");
